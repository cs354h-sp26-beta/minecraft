import { Quat } from "../lib/tsm/Quat.js";
import { MathUtils } from "../lib/threejs/build/three.module.js";

function toQuats(pose: [number, number, number, number][]): Quat[] {
  return pose.map((p) => new Quat(p));
}

function interpPoses(pose1: Quat[], pose2: Quat[], t: number): Quat[] {
  let result: Quat[] = [];
  for (let i = 0; i < pose1.length; i++) {
    result.push(Quat.slerpShort(pose1[i], pose2[i], t));
  }
  return result;
}

function makeAnimation(
  poses: Quat[][],
  times: number[],
  length: number,
  loop: boolean,
): (t: number) => Quat[] {
  return (t: number) => {
    poses.push(loop ? poses[0] : poses[poses.length - 1]);
    times.push(length);

    t = loop ? t % length : MathUtils.clamp(t, 0, length);
    let i = 0;
    while (i < times.length && times[i] < t) {
      i++;
    }

    let i1 = Math.max(0, i - 1);
    return interpPoses(
      poses[i1],
      poses[i],
      (t - times[i1]) / (times[i] - times[i1]),
    );
  };
}

